from typing import List, Optional
from pydantic import BaseModel, Field, field_validator


class LLMFinding(BaseModel):
    """
    Structured Pydantic model for individual code review findings generated by an LLM provider.
    """
    category: str = Field(..., description="Category: 'security' or 'quality'")
    severity: str = Field(..., description="Severity level: CRITICAL, HIGH, MEDIUM, LOW, INFO")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence score between 0.0 and 1.0")
    file: str = Field(..., description="Filename being reviewed")
    line: Optional[int] = Field(None, description="Line number of finding in changed code, or null if general")
    message: str = Field(..., description="Short finding summary title")
    explanation: str = Field(..., description="Detailed explanation of the issue")
    suggestion: str = Field(..., description="Actionable recommendation or refactored code suggestion")
    evidence: str = Field(..., description="Exact code snippet or line evidence from supplied code")

    @field_validator("severity")

    def validate_severity(cls, v: str) -> str:
        valid_severities = {"CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"}
        upper = v.upper().strip()
        if upper not in valid_severities:
            return "MEDIUM"
        return upper

    @field_validator("category")

    def validate_category(cls, v: str) -> str:
        lower = v.lower().strip()
        if lower not in {"security", "quality"}:
            return "quality"
        return lower

    @field_validator("evidence")

    def validate_evidence(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Evidence must be provided from the supplied code.")
        return v.strip()


class LLMReviewResponse(BaseModel):
    """
    Structured container for LLM review outputs.
    """
    findings: List[LLMFinding] = Field(default_factory=list)
