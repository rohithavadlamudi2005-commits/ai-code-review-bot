from typing import List, Tuple, Dict, Any, Optional
from app.services.review_service import CombinedFinding, ReviewPRResponse


SEVERITY_EMOJIS = {
    "CRITICAL": "🔴",
    "HIGH": "🟠",
    "MEDIUM": "🟡",
    "LOW": "🔵",
    "INFO": "⚪"
}


class GitHubReviewFormatter:
    """
    Formats AI Code Review findings into GitHub Markdown summaries and inline comment objects.
    """

    @staticmethod
    def format_review_summary(
        findings: List[CombinedFinding],
        severity_counts: Dict[str, int],
        analyzed_files_count: int,
        skipped_files_count: int
    ) -> str:
        """
        Generates a clean, professional GitHub PR review Markdown summary body.
        """
        total = len(findings)
        lines = ["## 🤖 AI Code Review\n"]

        if total == 0:
            lines.append("### Summary\n")
            lines.append(f"✓ **Clean Code Review!** No security or quality issues detected across {analyzed_files_count} analyzed file(s).\n")
            lines.append("---\n*Generated by AI Code Review Bot.*")
            return "\n".join(lines)

        lines.append("### Summary\n")
        lines.append(f"Found **{total} issue(s)** requiring attention across **{analyzed_files_count} analyzed file(s)**.\n")

        lines.append("| Severity | Count |")
        lines.append("|---|---|")
        for sev in ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]:
            cnt = severity_counts.get(sev, 0)
            lines.append(f"| {SEVERITY_EMOJIS.get(sev, '⚪')} {sev.capitalize()} | {cnt} |")

        lines.append("\n### Key Findings\n")

        for idx, f in enumerate(findings, start=1):
            emoji = SEVERITY_EMOJIS.get(f.severity, "⚪")
            lines.append(f"#### {emoji} {f.severity} — {f.message}")
            lines.append(f"**File:** `{f.file}`" + (f" | **Line:** `{f.line}`" if f.line else ""))
            lines.append(f"**Source:** `{f.source.upper()}`" + (f" (Rule: `{f.static_rule_id}`)" if f.static_rule_id else ""))
            lines.append(f"\n**Explanation:**\n{f.explanation}")
            lines.append(f"\n**Suggested Fix:**\n```\n{f.suggestion}\n```")
            lines.append("\n---")

        lines.append("\n*Generated by AI Code Review Bot.*")
        return "\n".join(lines)

    @staticmethod
    def prepare_inline_comments(findings: List[CombinedFinding]) -> Tuple[List[Dict[str, Any]], List[CombinedFinding]]:
        """
        Extracts valid inline comment payloads for findings that have a file and line number.
        Returns a tuple of (inline_comments_list, unplaced_findings_list).
        """
        inline_comments: List[Dict[str, Any]] = []
        unplaced_findings: List[CombinedFinding] = []

        for f in findings:
            if f.file and f.line and f.line > 0:
                comment_body = (
                    f"### {SEVERITY_EMOJIS.get(f.severity, '⚪')} [{f.severity}] {f.message}\n\n"
                    f"**Source:** `{f.source.upper()}`" + (f" (`{f.static_rule_id}`)" if f.static_rule_id else "") + "\n\n"
                    f"**Explanation:**\n{f.explanation}\n\n"
                    f"**Suggested Fix:**\n```\n{f.suggestion}\n```"
                )
                inline_comments.append({
                    "path": f.file,
                    "line": f.line,
                    "side": "RIGHT",
                    "body": comment_body
                })
            else:
                unplaced_findings.append(f)

        return inline_comments, unplaced_findings
